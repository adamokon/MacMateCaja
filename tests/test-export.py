#!/usr/bin/env python3
"""Regression checks for privacy export using only synthetic temporary files."""
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]


class ExportTest(unittest.TestCase):
    def setUp(self):
        self.fixture = tempfile.TemporaryDirectory(prefix='macmatecaja-export-test-')
        self.base = Path(self.fixture.name)
        self.root = self.base / 'project'
        for directory in ('scripts', 'tests', 'app', 'assets', 'config', 'public-docs',
                          'source/caja', 'source/gvfs', 'source/dconf',
                          'source/mate-desktop', 'source/mate-desktop-lite'):
            (self.root / directory).mkdir(parents=True, exist_ok=True)
        self.program = self.root / 'scripts/export-public.py'
        shutil.copyfile(ROOT / 'scripts/export-public.py', self.program)
        (self.root / 'config/config.example.ini').write_text('[places]\n')
        self.dest = self.base / 'release'

    def tearDown(self):
        self.fixture.cleanup()

    def run_export(self, *args):
        return subprocess.run([sys.executable, str(self.program), str(self.dest), *args],
                              capture_output=True, text=True, timeout=15)

    def test_assets_and_sources_unchanged(self):
        data = b'\x89PNG\r\n\x1a\nsynthetic image\x00\xff'
        (self.root / 'assets/icon.png').write_bytes(data)
        (self.root / 'source/caja/test.c').write_text('/* synthetic source */\n')
        (self.root / 'config/config.ini').write_text('[private]\n')
        result = self.run_export()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual((self.dest / 'assets/icon.png').read_bytes(), data)
        self.assertTrue((self.dest / 'scripts/export-public.py').is_file())
        self.assertTrue((self.dest / 'SOURCE-MANIFEST.json').is_file())
        self.assertFalse((self.dest / 'config/config.ini').exists())

    def test_excludes_generated_files(self):
        (self.root / 'source/caja/program').write_bytes(b'\xcf\xfa\xed\xfecompiled')
        (self.root / 'source/caja/wrapper').write_bytes(b'#!/bin/sh\n#' + b' Generated by libtool (GNU libtool)\n')
        (self.root / 'source/caja/sample.desktop').write_text('configured file')
        (self.root / 'source/caja/sample.desktop.in.in').write_text('template')
        result = self.run_export()
        self.assertEqual(result.returncode, 0, result.stderr)
        for name in ('program', 'wrapper', 'sample.desktop'):
            self.assertFalse((self.dest / 'source/caja' / name).exists())
        self.assertTrue((self.dest / 'source/caja/sample.desktop.in.in').exists())

    def test_private_paths_fail_audit(self):
        private = '/' + 'Users/' + 'synthetic-person/private'
        (self.root / 'source/caja/test.c').write_text(private)
        result = self.run_export()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Audit FAILED', result.stderr)
        self.assertNotIn(private, result.stderr)
        self.assertFalse((self.dest / 'SOURCE-MANIFEST.json').exists())

    def test_existing_destination_never_modified(self):
        self.dest.mkdir()
        sentinel = self.dest / 'sentinel'
        sentinel.write_text('keep me')
        result = self.run_export()
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(sentinel.read_text(), 'keep me')
        self.assertEqual(len(list(self.dest.iterdir())), 1)

    def test_external_symlink_rejected(self):
        external = self.base / 'external-secret'
        external.write_text('not exportable')
        (self.root / 'assets/link.txt').symlink_to(external)
        result = self.run_export()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Unsafe external symlink', result.stderr)
        self.assertFalse((self.dest / 'assets/link.txt').exists())


if __name__ == '__main__':
    unittest.main()
