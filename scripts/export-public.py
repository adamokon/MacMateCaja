#!/usr/bin/env python3
"""Copy a source-only release to a NEW directory. Never rewrite source/assets.

Local documentation and user profiles are deliberately not selected. Additional
private identifiers can be supplied with --deny; they are never written to the
release. Failed audits leave the candidate in place for inspection, not publication.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

EXCLUDED_DIRS = {'.git', '.deps', '.libs', 'autom4te.cache', 'build',
                 'build-macos', '__pycache__', '_CodeSignature'}
EXCLUDED_NAMES = {'Makefile', 'config.h', 'config.status', 'config.log',
                  'config.cache', 'libtool', 'stamp-h1', '.DS_Store',
                  'gschemas.compiled', '.meson-subproject-wrap-hash.txt',
                  'caja', 'caja-file-management-properties',
                  'caja-autorun-software', 'caja-connect-server',
                  'caja-src-marshal.c', 'caja-src-marshal.h',
                  'caja-enum-types.c', 'caja-enum-types.h',
                  'caja-resources.c', 'caja-resources.h'}
EXCLUDED_SUFFIXES = {'.o', '.lo', '.la', '.a', '.dylib', '.so', '.pyc', '.mo', '.log', '.valid'}
SOURCE_PROJECTS = ('caja', 'gvfs', 'dconf', 'mate-desktop', 'mate-desktop-lite')


def selected(path, relative):
    if any(p in EXCLUDED_DIRS for p in relative.parts):
        return False
    handmade = relative.parts[:2] == ('source', 'mate-desktop-lite')
    if path.name in EXCLUDED_NAMES and not (handmade and path.name in {'Makefile', 'config.h'}):
        return False
    if path.suffix in EXCLUDED_SUFFIXES or path.name.endswith('~'):
        return False
    if relative.as_posix() == 'source/caja/po/Makefile.in':
        return False # Generated from Makefile.in.in, embeds the build prefix.
    if (path.with_name(path.name + '.in').is_file() or
            path.with_name(path.name + '.in.in').is_file()):
        return False # Configured desktop/service/schema files; keep templates.
    head = path.read_bytes()[:4096]
    if head.startswith((b'\xcf\xfa\xed\xfe', b'\xfe\xed\xfa\xcf', b'\x7fELF')):
        return False
    if any(line.lower().startswith(b'# generated by libtool') for line in head.splitlines()):
        return False
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path)
    parser.add_argument('--deny', action='append', default=[])
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    dest = args.destination.absolute()
    if dest == root or root in dest.parents:
        parser.error('destination must be outside the working project')
    dest.mkdir(parents=True, exist_ok=False) # No deletion, no overwriting.
    mapping = []
    for name in SOURCE_PROJECTS:
        subtree = root / 'source' / name
        for path in sorted(subtree.rglob('*')):
            relative = path.relative_to(root)
            if path.is_file() and selected(path, relative):
                mapping.append((path, relative))
    for directory in ('app', 'assets', 'tests', 'scripts'):
        for path in sorted((root / directory).rglob('*')):
            relative = path.relative_to(root)
            if path.is_file() and selected(path, relative):
                mapping.append((path, relative))
    mapping.append((root / 'config/config.example.ini', Path('config/config.example.ini')))
    # Release metadata belongs at the root in both legacy and current layouts.
    for name in ('VERSION', 'CHANGELOG.md'):
        if (root / name).is_file():
            mapping.append((root / name, Path(name)))
    if (root / 'public-docs').is_dir():
        for path in sorted((root / 'public-docs').rglob('*')):
            if path.is_file():
                mapping.append((path, path.relative_to(root / 'public-docs')))
    else:
        # The published snapshot already has public documentation at its root.
        for name in ('README.md', 'LICENSE', 'LICENSE-NOTES.md', 'AUTHORS.md',
                     'CONTRIBUTING.md', 'AGENTS.md', '.gitignore'):
            if (root / name).is_file():
                mapping.append((root / name, Path(name)))
        for path in sorted((root / 'docs').rglob('*')):
            if path.is_file():
                mapping.append((path, path.relative_to(root)))
    for source, relative in mapping:
        if source.is_symlink():
            resolved = source.resolve()
            if root not in resolved.parents:
                raise SystemExit('Unsafe external symlink: ' + str(relative))
        target = dest / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target) # Do not propagate macOS extended attributes.
        target.chmod(source.stat().st_mode & 0o777)
    signatures = [re.compile(rb'/' + rb'Users/[^/\s\"\']+')]
    signatures += [re.compile(rb'(?<![A-Za-z0-9])' + re.escape(value.encode()) +
                              rb'(?![A-Za-z0-9])', re.I) for value in args.deny]
    violations = []
    hashes = {}
    for path in sorted(dest.rglob('*')):
        if not path.is_file():
            continue
        data = path.read_bytes()
        relative = path.relative_to(dest).as_posix()
        if any(pattern.search(data) or pattern.search(relative.encode()) for pattern in signatures):
            violations.append(relative)
        if data.startswith((b'\xcf\xfa\xed\xfe', b'\xfe\xed\xfa\xcf', b'\x7fELF')):
            violations.append(relative + ' (compiled executable)')
        hashes[relative] = hashlib.sha256(data).hexdigest()
    if violations:
        raise SystemExit('Audit FAILED; do not publish:\n' + '\n'.join(violations))
    (dest / 'SOURCE-MANIFEST.json').write_text(json.dumps(hashes, indent=2) + '\n')
    print(f'Audit passed: {len(hashes)} files; source/assets only. No history or user profiles copied.')
    print(dest)


if __name__ == '__main__':
    main()
